//! Reversible snapshot exclusion retains one owner through Cc, journal drain and lower completion.

use super::*;
use crate::irp::{ActorRequest, DataIoKind, ExecutionClass, PreparedRequest};
use crate::kernel::stream::{SnapshotLease, SnapshotPhase};
use crate::memory::DriverVec;
use crate::state::StreamCacheLease;

/// Keeps oplock responses and mandatory handle releases available while old mutations drain.
/// Paging is admitted only during writeback; new changes retain their captured IRPs until thaw.
pub(crate) fn snapshot_should_wait(owned: &mut OwnedIrp, phase: SnapshotPhase) -> bool {
    if phase == SnapshotPhase::Open {
        return false;
    }
    let execution = owned.execution_class();
    match owned.actor_request() {
        ActorRequest::Cleanup | ActorRequest::Close => false,
        ActorRequest::Captured(PreparedRequest::LockControl) => {
            execution != ExecutionClass::Release
        }
        ActorRequest::Captured(PreparedRequest::Read(read))
            if read.kind() == DataIoKind::Paging =>
        {
            phase == SnapshotPhase::Frozen
        }
        ActorRequest::Captured(PreparedRequest::Write(write))
            if write.kind() == DataIoKind::Paging =>
        {
            phase == SnapshotPhase::Frozen
        }
        ActorRequest::Captured(PreparedRequest::FileSystemControl(minor)) => {
            let minor = *minor;
            !matches!(
                crate::request::file_system_control::classify(owned.request(), minor),
                Ok(
                    crate::request::file_system_control::FsControlAdmission::User(
                        crate::irp::FsControlCode::RequestOplockLevel1
                            | crate::irp::FsControlCode::RequestOplockLevel2
                            | crate::irp::FsControlCode::RequestBatchOplock
                            | crate::irp::FsControlCode::OplockBreakAcknowledge
                            | crate::irp::FsControlCode::OplockBatchAckClosePending
                            | crate::irp::FsControlCode::OplockBreakNotify
                            | crate::irp::FsControlCode::OplockBreakAckNoLevel2
                            | crate::irp::FsControlCode::RequestFilterOplock
                            | crate::irp::FsControlCode::RequestOplock
                    )
                )
            )
        }
        _ => true,
    }
}

/// Pre-admission wait owns captures without acquiring a handle lane or mutation activity.
#[derive(Debug)]
struct SnapshotWait {
    /// Captured completion owner has acquired neither a mutation activity nor a handle lane.
    owned: OwnedIrp,
}

/// Retains a captured request outside mutation/handle ordering until snapshot exclusion ends.
/// # Errors
/// Returns allocation failure with the original IRP still owned.
pub(crate) fn wait_for_snapshot(
    owned: OwnedIrp,
) -> Result<Box<dyn CompletionOperation>, AdmitOperationError> {
    memory::boxed_try_map(owned, |owned| SnapshotWait { owned })
        .map(|operation| -> Box<dyn CompletionOperation> { operation })
        .map_err(|failure| {
            let (error, owned) = failure.into_parts();
            AdmitOperationError::new(error, owned)
        })
}
impl MountedVolumeOperation for SnapshotWait {
    fn advance_mounted(
        self: Box<Self>,
        event: CompletionEvent,
        access: &mut MountedVolumeAccess<'_>,
    ) -> OperationTransition {
        match event {
            CompletionEvent::Core(OperationEvent::CancelRequested) => {
                OperationTransition::Complete(
                    self.owned
                        .prepare_result(Err(Error::OperationCancelled.into())),
                )
            }
            CompletionEvent::Core(OperationEvent::Admitted) => {
                if access.storage_access().snapshot_phase() == SnapshotPhase::Open {
                    OperationTransition::ReadmitCaptured { owned: self.owned }
                } else {
                    OperationTransition::DeferOperation { suspended: self }
                }
            }
            _ => {
                crate::kernel::fatal::KernelWideInconsistency::completion_reactor_state_corruption()
                    .bugcheck()
            }
        }
    }
    fn record_mounted_storage_failure(
        &mut self,
        _failure: StorageFailureClass,
        _access: &mut MountedVolumeAccess<'_>,
    ) {
        crate::kernel::fatal::KernelWideInconsistency::completion_reactor_state_corruption()
            .bugcheck();
    }
}
impl_mounted_operation_adapter!(SnapshotWait);

/// Each phase owns the work that must end before freeze authority may be released.
#[derive(Debug)]
enum SnapshotPhaseWork {
    /// Admitted mutations may still publish streams required by the cache snapshot.
    Drain,
    /// One cache worker owns its stream; the rest remain retained here.
    Cache(DriverVec<StreamCacheLease>),
    /// Paging generated by Cc must checkpoint before the actor seals new paging.
    Clean,
    /// One final physical filesystem flush must finish before lower snapshot submission.
    Media(StorageRequestIdentity),
    /// A private cancellable lower snapshot IRP owns the exact completion boundary.
    Lower,
}
/// Freeze ownership cannot exist without the original upper completion owner.
#[derive(Debug)]
enum SnapshotState {
    /// No exclusion acquired yet; allocation and target checks can fail without effects.
    Ready(OwnedIrp),
    /// Original request, unique freeze authority and the current native/lower phase.
    Active {
        /// Sole upper completion owner.
        owned: OwnedIrp,
        /// Reversible exclusion retained until every admitted native/lower access ends.
        lease: SnapshotLease,
        /// Exact next completion expected by this owner.
        work: SnapshotPhaseWork,
    },
    /// Completion consumed both IRP and exclusion.
    Terminal,
}
/// Actor-owned barrier; lower controls use the reactor's existing cancellation/rundown protocol.
#[derive(Debug)]
struct SnapshotOperation {
    /// Stable mounted storage route retained by the suspended operation's VCB rundown.
    devices: MountedStorageRoute,
    /// Driver-owned device pins completion code independently from the lower target.
    completion_owner: crate::state::KernelDevice,
    /// Unique completion and freeze state.
    state: SnapshotState,
}

/// Validates a mounted volume target and allocates before changing native admission.
/// # Errors
/// Returns foreign handles, revoked durability, or allocation failure with the original IRP.
pub(crate) fn snapshot(
    mut owned: OwnedIrp,
    access: &MountedVolumeAccess<'_>,
) -> Result<Box<dyn CompletionOperation>, AdmitOperationError> {
    let target = owned.request().with_active(|active| {
        let stack = active.current_stack()?;
        match stack.file_object() {
            Ok(file) => {
                let volume = crate::state::OpenedVolume::decode(file)?;
                if !access.owns_volume(volume.volume()) {
                    return Err(DriverError::InvalidDeviceRequest);
                }
            }
            Err(DriverError::InvalidParameter) => {}
            Err(error) => return Err(error),
        }
        access.authorize_durability()?;
        Ok(active.device())
    });
    let completion_owner = match target {
        Ok(device) => device,
        Err(error) => return Err(AdmitOperationError::new(error, owned)),
    };
    let devices = access.storage_route();
    memory::boxed_try_map(owned, |owned| SnapshotOperation {
        devices,
        completion_owner,
        state: SnapshotState::Ready(owned),
    })
    .map(|operation| -> Box<dyn CompletionOperation> { operation })
    .map_err(|failure| {
        let (error, owned) = failure.into_parts();
        AdmitOperationError::new(error, owned)
    })
}
impl SnapshotOperation {
    /// Thaws only snapshot admission before upper acknowledgement; independent revocation persists.
    fn finish(
        owned: OwnedIrp,
        lease: SnapshotLease,
        result: DriverResult<IrpCompletion>,
    ) -> OperationTransition {
        drop(lease);
        OperationTransition::Complete(owned.prepare_result(result))
    }
    /// A native worker flushes one retained cache while the actor admits its paging writes.
    fn cache(
        mut self: Box<Self>,
        owned: OwnedIrp,
        lease: SnapshotLease,
        mut streams: DriverVec<StreamCacheLease>,
    ) -> OperationTransition {
        if let Some(stream) = streams.pop() {
            self.state = SnapshotState::Active {
                owned,
                lease,
                work: SnapshotPhaseWork::Cache(streams),
            };
            OperationTransition::SubmitPassiveWork {
                work: crate::irp::PassiveWork::flush(stream),
                suspended: self,
            }
        } else {
            self.state = SnapshotState::Active {
                owned,
                lease,
                work: SnapshotPhaseWork::Clean,
            };
            OperationTransition::Wait {
                condition: WaitCondition::JournalClean,
                suspended: self,
            }
        }
    }
    /// No cache, mutation or checkpoint can dirty the consistent image while this control runs.
    fn lower(mut self: Box<Self>, owned: OwnedIrp, lease: SnapshotLease) -> OperationTransition {
        self.state = SnapshotState::Active {
            owned,
            lease,
            work: SnapshotPhaseWork::Lower,
        };
        OperationTransition::SubmitDeviceControl {
            query: crate::kernel::storage::DeviceControlKind::SnapshotHold,
            completion_owner: self.completion_owner,
            target: self.devices.filesystem_control_device(),
            suspended: self,
        }
    }
}
impl MountedVolumeOperation for SnapshotOperation {
    fn advance_mounted(
        mut self: Box<Self>,
        event: CompletionEvent,
        access: &mut MountedVolumeAccess<'_>,
    ) -> OperationTransition {
        let state = core::mem::replace(&mut self.state, SnapshotState::Terminal);
        match (state, event) {
            (SnapshotState::Ready(owned), CompletionEvent::Core(OperationEvent::Admitted)) => {
                let mut lease = match access.storage_access().begin_snapshot() {
                    Ok(lease) => lease,
                    Err(error) => {
                        return OperationTransition::Complete(owned.prepare_result(Err(error)));
                    }
                };
                if access.mounted_profile().access() == ext4_core::MediaAccess::ReadOnly {
                    lease.seal();
                    return self.lower(owned, lease);
                }
                self.state = SnapshotState::Active {
                    owned,
                    lease,
                    work: SnapshotPhaseWork::Drain,
                };
                OperationTransition::Wait {
                    condition: WaitCondition::JournalClean,
                    suspended: self,
                }
            }
            (
                SnapshotState::Ready(owned),
                CompletionEvent::Core(OperationEvent::CancelRequested),
            ) => OperationTransition::Complete(
                owned.prepare_result(Err(Error::OperationCancelled.into())),
            ),
            (
                SnapshotState::Active {
                    owned,
                    lease,
                    work: SnapshotPhaseWork::Drain,
                },
                CompletionEvent::BarrierReleased(permit),
            ) => {
                if permit.into_identity() != 1 {
                    return Self::finish(
                        owned,
                        lease,
                        Err(DriverError::InternalInvariantViolation),
                    );
                }
                match access.prepare_cache_writeback() {
                    Ok(streams) => self.cache(owned, lease, streams),
                    Err(error) => Self::finish(owned, lease, Err(error)),
                }
            }
            (
                SnapshotState::Active {
                    owned,
                    lease,
                    work: SnapshotPhaseWork::Cache(streams),
                },
                CompletionEvent::PassiveCompleted(crate::irp::PassiveWorkCompletion::Flush(result)),
            ) => match result {
                Ok(()) => self.cache(owned, lease, streams),
                Err(error) => {
                    record_cache_coherency_failure(error, access);
                    Self::finish(owned, lease, Err(error))
                }
            },
            (
                SnapshotState::Active {
                    owned,
                    mut lease,
                    work: SnapshotPhaseWork::Clean,
                },
                CompletionEvent::BarrierReleased(permit),
            ) => {
                if permit.into_identity() != 1 {
                    return Self::finish(
                        owned,
                        lease,
                        Err(DriverError::InternalInvariantViolation),
                    );
                }
                lease.seal();
                let request = StorageRequest::Flush {
                    target: ext4_core::StorageTarget::Filesystem,
                };
                let expected = StorageRequestIdentity::from_request(&request);
                self.state = SnapshotState::Active {
                    owned,
                    lease,
                    work: SnapshotPhaseWork::Media(expected),
                };
                OperationTransition::SubmitLower {
                    devices: self.devices,
                    request,
                    suspended: self,
                }
            }
            (
                SnapshotState::Active {
                    owned,
                    lease,
                    work: SnapshotPhaseWork::Media(expected),
                },
                CompletionEvent::Core(OperationEvent::StorageCompleted(completion)),
            ) => match expected.complete(completion) {
                Ok(()) => self.lower(owned, lease),
                Err(error) => Self::finish(owned, lease, Err(error.into())),
            },
            (
                SnapshotState::Active {
                    owned,
                    lease,
                    work: SnapshotPhaseWork::Lower,
                },
                CompletionEvent::SnapshotCompleted(status),
            ) => Self::finish(owned, lease, Ok(IrpCompletion::native_status(status))),
            (
                SnapshotState::Active { owned, lease, .. },
                CompletionEvent::Core(OperationEvent::CancelRequested),
            ) => Self::finish(owned, lease, Err(Error::OperationCancelled.into())),
            (SnapshotState::Active { owned, lease, .. }, CompletionEvent::VolumeFailed(error)) => {
                Self::finish(owned, lease, Err(error))
            }
            _ => {
                crate::kernel::fatal::KernelWideInconsistency::completion_reactor_state_corruption()
                    .bugcheck()
            }
        }
    }
    fn record_mounted_storage_failure(
        &mut self,
        failure: StorageFailureClass,
        access: &mut MountedVolumeAccess<'_>,
    ) {
        if let StorageFailureClass::DurabilityUnknown { .. } = failure {
            access.record_cache_writeback_failure(wdk_sys::STATUS_IO_DEVICE_ERROR);
        }
    }
}
impl_mounted_operation_adapter!(SnapshotOperation);
