/// Dispatches one IRP through the unified completion-driven receive boundary.
/// # Safety
///
/// `device` and `irp` must be the live objects supplied to the active callback for `major`.
#[expect(
    unsafe_code,
    reason = "this audited kernel or raw-memory item documents each unsafe operation with a local SAFETY invariant"
)]
unsafe fn dispatch(device: PDEVICE_OBJECT, irp: PIRP, major: DispatchMajor) -> NTSTATUS {
    let received = match unsafe {
        // SAFETY: The callback caller retains the WDK-provided device and IRP for this transition.
        ReceivedIrp::decode(device, irp)
    } {
        Ok(received) => received,
        Err(error) => {
            return unsafe {
                // SAFETY: The same callback contract retains a non-null IRP for error completion.
                ReceivedIrp::complete_decode_error(irp, error)
            };
        }
    };

    let device_kind = match crate::state::driver_device_kind(received.device()) {
        Ok(device_kind) => device_kind,
        Err(error) => return received.complete_result(Err(error)),
    };
    if device_kind == DriverDeviceKind::MountedVolume
        && matches!(major, DispatchMajor::Read | DispatchMajor::Write)
    {
        let mut received = received;
        let action = received.with_active(|active| {
            active
                .current_stack()?
                .mdl_action(major == DispatchMajor::Write)
        });
        let completion = match action {
            Ok(Some(crate::irp::MdlAction::ReadComplete)) => Some(crate::irp::MdlCompletion::Read),
            Ok(Some(crate::irp::MdlAction::WriteComplete)) => {
                Some(crate::irp::MdlCompletion::Write)
            }
            Ok(_) => None,
            Err(error) => return received.complete_result(Err(error)),
        };
        if let Some(completion) = completion {
            return received.delegate_mdl_completion(completion);
        }
        return dispatch_received(received, device_kind, major);
    }
    dispatch_received(received, device_kind, major)
}

/// Routes an IRP after any allocation-free MDL completion delegation.
fn dispatch_received(
    received: crate::irp::ReceivedIrp,
    device_kind: DriverDeviceKind,
    major: DispatchMajor,
) -> NTSTATUS {
    match dispatch_policy(device_kind, major) {
        DispatchPolicy::Immediate(request) => execute_immediate(received, request),
        DispatchPolicy::Queued => crate::state::queue_device_request(received, major),
    }
}

/// Immediate request semantics selected from both the device kind and IRP major function.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
enum ImmediateDispatch {
    /// Device-scoped storage removal and original-IRP lower delegation.
    PlugAndPlay,
    /// Transfer a direct-volume control IRP to its immutable lower storage route.
    ForwardVolumeControl,
    /// Establishes an uncontextualized handle to the secured control device.
    OpenControl,
    /// Releases per-handle control cleanup state; no such state is retained.
    CleanupControl,
    /// Releases one control FILE_OBJECT; no driver context is attached.
    CloseControl,
    /// Decodes the one private lifecycle request accepted by the control device.
    ControlDeviceRequest,
    /// Completes an unsupported request without entering a device actor.
    Reject,
}

/// Queue policy for a received major function.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
enum DispatchPolicy {
    /// Complete one explicitly selected request during the dispatch callback.
    Immediate(ImmediateDispatch),
    /// Mark pending and execute on the dedicated device actor.
    Queued,
}

/// Returns the queue policy for a major function.
const fn dispatch_policy(device_kind: DriverDeviceKind, major: DispatchMajor) -> DispatchPolicy {
    match device_kind {
        DriverDeviceKind::Control => match major {
            DispatchMajor::Create => DispatchPolicy::Immediate(ImmediateDispatch::OpenControl),
            DispatchMajor::Cleanup => DispatchPolicy::Immediate(ImmediateDispatch::CleanupControl),
            DispatchMajor::Close => DispatchPolicy::Immediate(ImmediateDispatch::CloseControl),
            DispatchMajor::DeviceControl => {
                DispatchPolicy::Immediate(ImmediateDispatch::ControlDeviceRequest)
            }
            DispatchMajor::FileSystemControl => DispatchPolicy::Queued,
            DispatchMajor::Read
            | DispatchMajor::Write
            | DispatchMajor::QueryInformation
            | DispatchMajor::SetInformation
            | DispatchMajor::QueryVolumeInformation
            | DispatchMajor::SetVolumeInformation
            | DispatchMajor::DirectoryControl
            | DispatchMajor::FlushBuffers
            | DispatchMajor::QueryEa
            | DispatchMajor::SetEa
            | DispatchMajor::LockControl
            | DispatchMajor::Shutdown
            | DispatchMajor::PlugAndPlay
            | DispatchMajor::QuerySecurity
            | DispatchMajor::SetSecurity => DispatchPolicy::Immediate(ImmediateDispatch::Reject),
        },
        DriverDeviceKind::MountedVolume => match major {
            DispatchMajor::PlugAndPlay => DispatchPolicy::Immediate(ImmediateDispatch::PlugAndPlay),
            DispatchMajor::DeviceControl => {
                DispatchPolicy::Immediate(ImmediateDispatch::ForwardVolumeControl)
            }
            DispatchMajor::Create
            | DispatchMajor::Cleanup
            | DispatchMajor::Close
            | DispatchMajor::Read
            | DispatchMajor::Write
            | DispatchMajor::QueryInformation
            | DispatchMajor::SetInformation
            | DispatchMajor::QueryVolumeInformation
            | DispatchMajor::SetVolumeInformation
            | DispatchMajor::DirectoryControl
            | DispatchMajor::FileSystemControl
            | DispatchMajor::FlushBuffers
            | DispatchMajor::QueryEa
            | DispatchMajor::SetEa
            | DispatchMajor::LockControl
            | DispatchMajor::QuerySecurity
            | DispatchMajor::SetSecurity
            | DispatchMajor::Shutdown => DispatchPolicy::Queued,
        },
    }
}

/// Executes immediate control semantics, consuming the IRP by completion or lower delegation.
fn execute_immediate(mut received: ReceivedIrp, request: ImmediateDispatch) -> NTSTATUS {
    if request == ImmediateDispatch::PlugAndPlay {
        let minor = received.with_active(|active| Ok(active.current_stack()?.pnp_minor()));
        return match minor {
            Ok(crate::irp::PnpMinor::QueryRemove) => {
                crate::state::queue_device_request(received, DispatchMajor::PlugAndPlay)
            }
            Ok(minor) => crate::state::MountedVolumeDevice::dispatch_pnp(received, minor),
            Err(error) => received.complete_result(Err(error)),
        };
    }
    if request == ImmediateDispatch::ForwardVolumeControl {
        let lower = received.with_active(|active| {
            let current = active.current_stack()?;
            let stack = current.device_control()?;
            // Snapshot freeze needs a filesystem durability barrier before lower submission.
            if stack.io_control_code() == IOCTL_VOLSNAP_FLUSH_AND_HOLD_WRITES {
                return Err(DriverError::NotSupported);
            }
            let volume = crate::state::OpenedVolume::decode(current.file_object()?)?;
            volume.control_device()
        });
        return match lower {
            Ok(lower) => crate::state::MountedVolumeDevice::forward_volume_control(received, lower),
            Err(error) => received.complete_result(Err(error)),
        };
    }
    let result = match request {
        ImmediateDispatch::OpenControl
        | ImmediateDispatch::CleanupControl
        | ImmediateDispatch::CloseControl => Ok(IrpCompletion::EMPTY),
        ImmediateDispatch::ControlDeviceRequest => {
            let stack = received.with_active(|active| active.current_stack()?.device_control());
            stack.and_then(|stack| {
                if !stack.is_payload_free() {
                    return Err(DriverError::InvalidParameter);
                }
                if stack.io_control_code() != crate::lifecycle_control::PREPARE_UNLOAD_IOCTL {
                    return Err(DriverError::InvalidDeviceRequest);
                }
                crate::state::ControlDevice::prepare_unload(received.device())?;
                Ok(IrpCompletion::EMPTY)
            })
        }
        ImmediateDispatch::Reject
        | ImmediateDispatch::ForwardVolumeControl
        | ImmediateDispatch::PlugAndPlay => Err(DriverError::InvalidDeviceRequest),
    };
    received.complete_result(result)
}

/// Selects the scheduler lane shared by requests that remain legal across CLEANUP.
/// # Errors
///
/// Returns `FileClosed` after CLOSE has begun consuming the handle lane.
fn post_cleanup_lane(
    state: HandleAdmissionState,
    request: PostCleanupRequest,
) -> DriverResult<HandleOperationLane> {
    match state {
        HandleAdmissionState::OpenHandle
        | HandleAdmissionState::CleanupDraining
        | HandleAdmissionState::CleanedHandle => Ok(HandleOperationLane::PostCleanup(request)),
        HandleAdmissionState::ClosingHandle | HandleAdmissionState::ClosedHandle => {
            Err(DriverError::FileClosed)
        }
    }
}

/// Converts one CSQ-owned request into a concrete consuming operation.
///
/// Classification is copied out before `owned` moves so no pointer into queue metadata can enter
/// an operation or lower completion envelope.
/// # Errors
///
/// Returns the still-owned IRP when lifecycle admission, request decoding, operation allocation,
/// or mounted-state validation fails.
pub(crate) fn admit_owned(
    mut owned: OwnedIrp,
    target: &mut ReactorTarget,
    trace: crate::kernel::operational_trace::OperationalTrace,
    finalization: &mut crate::irp::FinalizationPool,
) -> Result<AdmittedOperation, AdmitOperationError> {
    if !matches!(
        owned.actor_request(),
        ActorRequest::Cleanup | ActorRequest::Close
    ) && let ReactorTarget::MountedVolume(_) = target
        && let Err(error) = target.with_mounted_access(|access| access.authorize_storage())
    {
        return Err(AdmitOperationError::new(error, owned));
    }
    #[derive(Clone, Copy, Debug, Eq, PartialEq)]
    enum HandleRequestClass {
        Device,
        Ordinary,
        Paging,
        FlushBuffers,
        Cleanup,
        Close,
    }

    enum LifecyclePublication {
        None,
        Cleanup(crate::state::PreparedHandleAdmission),
        Close(crate::state::PreparedHandleAdmission),
    }

    enum Admission {
        QueryRemove,
        Cleanup,
        Close,
        Mdl(crate::irp::MdlTransfer),
        Mount(super::file_system_control::MountAdmission),
        Read(ReadRequestKind),
        Directory,
        Raw(crate::state::RawVolumeOperationKind),
        Mutation(MutationRequestKind),
        Flush,
        VolumeClose(super::operation::VolumeCloseRequest),
        Immediate(ImmediateRequestKind),
        Notification,
        ByteRangeLock,
        OplockControl,
        VolumeControl(super::operation::VolumeControlRequestKind),
        VolumeQuery,
        FsControl(crate::irp::FileSystemControlMinorFunction),
        Unsupported,
    }

    let admission = match owned.actor_request() {
        ActorRequest::Captured(PreparedRequest::Mdl(action)) => Admission::Mdl(*action),
        ActorRequest::Captured(PreparedRequest::Read(_)) => Admission::Read(ReadRequestKind::Read),
        ActorRequest::Captured(PreparedRequest::QueryInformation) => {
            Admission::Read(ReadRequestKind::QueryInformation)
        }
        ActorRequest::Captured(PreparedRequest::DirectoryControl(
            PreparedDirectoryControl::QueryDirectory(_),
        )) => Admission::Directory,
        ActorRequest::Captured(PreparedRequest::QueryEa(_)) => {
            Admission::Read(ReadRequestKind::QueryEa)
        }
        ActorRequest::Captured(PreparedRequest::QuerySecurity { .. }) => {
            Admission::Read(ReadRequestKind::QuerySecurity)
        }
        ActorRequest::Captured(PreparedRequest::QueryVolumeInformation) => Admission::VolumeQuery,
        ActorRequest::Captured(PreparedRequest::Create) => {
            Admission::Mutation(MutationRequestKind::Create)
        }
        ActorRequest::Captured(PreparedRequest::Write(_)) => {
            Admission::Mutation(MutationRequestKind::Write)
        }
        ActorRequest::Captured(PreparedRequest::SetInformation) => {
            Admission::Mutation(MutationRequestKind::SetInformation)
        }
        ActorRequest::Captured(PreparedRequest::SetEa) => {
            Admission::Mutation(MutationRequestKind::SetEa)
        }
        ActorRequest::Captured(PreparedRequest::SetSecurity { .. }) => {
            Admission::Mutation(MutationRequestKind::SetSecurity)
        }
        ActorRequest::Captured(PreparedRequest::SetVolumeInformation) => {
            Admission::Mutation(MutationRequestKind::SetVolumeInformation)
        }
        ActorRequest::Cleanup => Admission::Cleanup,
        ActorRequest::Captured(PreparedRequest::FlushBuffers) => Admission::Flush,
        ActorRequest::Captured(PreparedRequest::Shutdown) => {
            Admission::VolumeClose(super::operation::VolumeCloseRequest::Shutdown)
        }
        ActorRequest::Captured(PreparedRequest::QueryRemove) => Admission::QueryRemove,
        ActorRequest::Close => Admission::Close,
        ActorRequest::Captured(PreparedRequest::DirectoryControl(
            PreparedDirectoryControl::NotifyChangeDirectory,
        )) => Admission::Notification,
        ActorRequest::Captured(PreparedRequest::LockControl) => Admission::ByteRangeLock,
        ActorRequest::Captured(PreparedRequest::RetrievalPointers { .. }) => {
            Admission::Read(ReadRequestKind::GetRetrievalPointers)
        }
        ActorRequest::Captured(PreparedRequest::FileSystemControl(minor)) => {
            Admission::FsControl(*minor)
        }
    };

    let admission = match admission {
        Admission::FsControl(minor) => {
            let classified = match super::file_system_control::classify(owned.request(), minor) {
                Ok(classified) => classified,
                Err(error) => return Err(AdmitOperationError::new(error, owned)),
            };
            match classified {
                super::file_system_control::FsControlAdmission::Mount(mount) => {
                    Admission::Mount(mount)
                }
                super::file_system_control::FsControlAdmission::Unsupported => {
                    Admission::Unsupported
                }
                super::file_system_control::FsControlAdmission::User(code) => match code {
                    crate::irp::FsControlCode::RequestOplockLevel1
                    | crate::irp::FsControlCode::RequestOplockLevel2
                    | crate::irp::FsControlCode::RequestBatchOplock
                    | crate::irp::FsControlCode::OplockBreakAcknowledge
                    | crate::irp::FsControlCode::OplockBatchAckClosePending
                    | crate::irp::FsControlCode::OplockBreakNotify
                    | crate::irp::FsControlCode::OplockBreakAckNoLevel2
                    | crate::irp::FsControlCode::RequestFilterOplock
                    | crate::irp::FsControlCode::RequestOplock => Admission::OplockControl,
                    crate::irp::FsControlCode::GetRetrievalPointers => Admission::Unsupported,
                    crate::irp::FsControlCode::GetReparsePoint => {
                        Admission::Read(ReadRequestKind::GetReparsePoint)
                    }
                    crate::irp::FsControlCode::SetReparsePoint => {
                        Admission::Mutation(MutationRequestKind::SetReparsePoint)
                    }
                    crate::irp::FsControlCode::DeleteReparsePoint => {
                        Admission::Mutation(MutationRequestKind::DeleteReparsePoint)
                    }
                    crate::irp::FsControlCode::EnableVerity => {
                        Admission::Mutation(MutationRequestKind::EnableVerity)
                    }
                    crate::irp::FsControlCode::AddEncryptionKey => {
                        Admission::Mutation(MutationRequestKind::AddEncryptionKey)
                    }
                    crate::irp::FsControlCode::RemoveEncryptionKey => {
                        Admission::Mutation(MutationRequestKind::RemoveEncryptionKey)
                    }
                    crate::irp::FsControlCode::GetEncryptionKeyStatus => {
                        Admission::Immediate(ImmediateRequestKind::GetEncryptionKeyStatus)
                    }
                    crate::irp::FsControlCode::LockVolume => {
                        Admission::VolumeControl(super::operation::VolumeControlRequestKind::Lock)
                    }
                    crate::irp::FsControlCode::UnlockVolume => {
                        Admission::VolumeControl(super::operation::VolumeControlRequestKind::Unlock)
                    }
                    crate::irp::FsControlCode::DismountVolume => {
                        Admission::VolumeClose(super::operation::VolumeCloseRequest::Dismount)
                    }
                    crate::irp::FsControlCode::IsVolumeMounted => Admission::VolumeControl(
                        super::operation::VolumeControlRequestKind::IsMounted,
                    ),
                    crate::irp::FsControlCode::AllowExtendedDasdIo => Admission::VolumeControl(
                        super::operation::VolumeControlRequestKind::AllowExtendedDasdIo,
                    ),
                },
            }
        }
        admission => admission,
    };

    let data_io_kind = match owned.actor_request() {
        ActorRequest::Captured(PreparedRequest::Read(read)) => Some(read.kind()),
        ActorRequest::Captured(PreparedRequest::Write(write)) => Some(write.kind()),
        _ => None,
    };
    let raw_kind = match (&admission, data_io_kind) {
        (Admission::Read(ReadRequestKind::Read), Some(DataIoKind::Handle)) => {
            Some(crate::state::RawVolumeOperationKind::Read)
        }
        (Admission::Mutation(MutationRequestKind::Write), Some(DataIoKind::Handle)) => {
            Some(crate::state::RawVolumeOperationKind::Write)
        }
        _ => None,
    };
    let admission = if let Some(kind) = raw_kind {
        match super::file_info::is_direct_volume_data(owned.request()) {
            Ok(true) => Admission::Raw(kind),
            Ok(false) => admission,
            Err(error) => return Err(AdmitOperationError::new(error, owned)),
        }
    } else {
        admission
    };
    let handle_class = match &admission {
        Admission::Mdl(_) => HandleRequestClass::Ordinary,
        Admission::Mount(_) | Admission::QueryRemove => HandleRequestClass::Device,
        Admission::Read(ReadRequestKind::Read) if data_io_kind == Some(DataIoKind::Paging) => {
            HandleRequestClass::Paging
        }
        Admission::Directory | Admission::Read(_) | Admission::Raw(_) | Admission::VolumeQuery => {
            HandleRequestClass::Ordinary
        }
        Admission::Mutation(MutationRequestKind::Create) => HandleRequestClass::Device,
        Admission::Mutation(MutationRequestKind::Write)
            if data_io_kind == Some(DataIoKind::Paging) =>
        {
            HandleRequestClass::Paging
        }
        Admission::Cleanup => HandleRequestClass::Cleanup,
        Admission::Mutation(_) => HandleRequestClass::Ordinary,
        Admission::Flush => HandleRequestClass::FlushBuffers,
        Admission::VolumeClose(super::operation::VolumeCloseRequest::Shutdown) => {
            HandleRequestClass::Device
        }
        Admission::VolumeClose(super::operation::VolumeCloseRequest::Dismount) => {
            HandleRequestClass::Ordinary
        }
        Admission::Close => HandleRequestClass::Close,
        Admission::Immediate(_)
        | Admission::Notification
        | Admission::ByteRangeLock
        | Admission::OplockControl
        | Admission::VolumeControl(_) => HandleRequestClass::Ordinary,
        Admission::FsControl(_) | Admission::Unsupported => HandleRequestClass::Device,
    };

    let (operation_admission, lifecycle_publication) = if matches!(
        handle_class,
        HandleRequestClass::Device | HandleRequestClass::Paging
    ) {
        (OperationAdmission::Device, LifecyclePublication::None)
    } else {
        let prepared = match super::file_info::prepare_handle_admission(owned.request()) {
            Ok(prepared) => prepared,
            Err(error) => return Err(AdmitOperationError::new(error, owned)),
        };
        match prepared {
            None if handle_class == HandleRequestClass::Close => {
                (OperationAdmission::Device, LifecyclePublication::None)
            }
            None => {
                return Err(AdmitOperationError::new(
                    DriverError::InvalidParameter,
                    owned,
                ));
            }
            Some(prepared) => {
                let file_object = prepared.file_object();
                let state = prepared.state();
                match handle_class {
                    HandleRequestClass::Ordinary => {
                        if state != HandleAdmissionState::OpenHandle {
                            return Err(AdmitOperationError::new(DriverError::FileClosed, owned));
                        }
                        (
                            OperationAdmission::Handle {
                                file_object,
                                lane: HandleOperationLane::Ordinary,
                            },
                            LifecyclePublication::None,
                        )
                    }
                    HandleRequestClass::FlushBuffers => {
                        let lane = match post_cleanup_lane(state, PostCleanupRequest::FlushBuffers)
                        {
                            Ok(lane) => lane,
                            Err(error) => return Err(AdmitOperationError::new(error, owned)),
                        };
                        (
                            OperationAdmission::Handle { file_object, lane },
                            LifecyclePublication::None,
                        )
                    }
                    HandleRequestClass::Cleanup => {
                        if !matches!(
                            state,
                            HandleAdmissionState::OpenHandle
                                | HandleAdmissionState::CleanupDraining
                        ) {
                            return Err(AdmitOperationError::new(DriverError::FileClosed, owned));
                        }
                        (
                            OperationAdmission::Handle {
                                file_object,
                                lane: HandleOperationLane::Cleanup,
                            },
                            LifecyclePublication::Cleanup(prepared),
                        )
                    }
                    HandleRequestClass::Close => (
                        OperationAdmission::Handle {
                            file_object,
                            lane: HandleOperationLane::PostCleanup(PostCleanupRequest::Close),
                        },
                        LifecyclePublication::Close(prepared),
                    ),
                    HandleRequestClass::Device | HandleRequestClass::Paging => {
                        (OperationAdmission::Device, LifecyclePublication::None)
                    }
                }
            }
        }
    };

    let operation =
        match admission {
            Admission::QueryRemove => {
                target.with_mounted_access(|_| super::operation::query_remove(owned))
            }
            Admission::Cleanup => {
                Ok(finalization.activate(crate::irp::FinalizationRequest::Cleanup, owned))
            }
            Admission::Close => {
                Ok(finalization.activate(crate::irp::FinalizationRequest::Close, owned))
            }
            Admission::Mdl(action) => {
                target.with_mounted_access(|access| super::operation::mdl(owned, action, access))
            }
            Admission::Mount(admission) => {
                target.require_control_device();
                super::operation::mount(owned, admission, trace)
            }
            Admission::Directory => target
                .with_mounted_access(|access| super::operation::query_directory(owned, access)),
            Admission::Read(kind) => {
                target.with_mounted_access(|access| super::operation::read(owned, kind, access))
            }
            Admission::Raw(kind) => target
                .with_mounted_access(|access| super::operation::raw_volume(owned, kind, access)),
            Admission::Mutation(kind) => {
                target.with_mounted_access(|access| super::operation::mutation(owned, kind, access))
            }
            Admission::Flush => {
                target.with_mounted_access(|access| super::operation::flush(owned, access))
            }
            Admission::VolumeClose(kind) => target
                .with_mounted_access(|access| super::operation::volume_close(owned, kind, access)),
            Admission::Immediate(kind) => {
                target.with_mounted_access(|_| super::operation::immediate(owned, kind))
            }
            Admission::VolumeQuery => {
                target.with_mounted_access(|_| super::volume_info::query(owned))
            }
            Admission::Notification => {
                target.with_mounted_access(|_| super::operation::notification(owned))
            }
            Admission::ByteRangeLock => target
                .with_mounted_access(|access| super::operation::byte_range_lock(owned, access)),
            Admission::OplockControl => {
                target.with_mounted_access(|_| super::operation::oplock_control(owned))
            }
            Admission::VolumeControl(kind) => {
                target.with_mounted_access(|_| super::operation::volume_control(owned, kind))
            }
            Admission::FsControl(_) => Err(AdmitOperationError::new(
                DriverError::InternalInvariantViolation,
                owned,
            )),
            Admission::Unsupported => Err(AdmitOperationError::new(
                DriverError::InvalidDeviceRequest,
                owned,
            )),
        }?;
    match lifecycle_publication {
        LifecyclePublication::None => {}
        LifecyclePublication::Cleanup(prepared) => prepared.begin_cleanup(),
        LifecyclePublication::Close(prepared) => prepared.begin_close(),
    }
    Ok(AdmittedOperation::new(operation, operation_admission))
}

#[cfg(test)]
mod tests {
    /// # Panics
    ///
    /// Panics if mounted-volume controls select mailbox execution instead of lower delegation.
    #[test]
    fn mounted_volume_controls_select_lower_delegation() {
        assert_eq!(
            dispatch_policy(
                DriverDeviceKind::MountedVolume,
                DispatchMajor::DeviceControl
            ),
            DispatchPolicy::Immediate(ImmediateDispatch::ForwardVolumeControl)
        );
    }
    use crate::{
        irp::{
            DispatchMajor,
            reactor::{HandleOperationLane, PostCleanupRequest},
        },
        kernel::status::DriverError,
        state::{DriverDeviceKind, HandleAdmissionState},
    };

    use super::{DispatchPolicy, ImmediateDispatch, dispatch_policy, post_cleanup_lane};

    /// Keeps the production operation-construction graph inside the unit-test reachability set.
    ///
    /// # Panics
    ///
    /// This test has no runtime failure path. Compilation fails if the concrete admission boundary
    /// is removed or changes into a compatibility facade.
    #[test]
    fn operation_admission_boundary_remains_linked() {
        let boundary = super::admit_owned;
        let _ = boundary;
    }

    /// # Panics
    ///
    /// Panics when the shutdown request stops using the passive-level queue.
    #[test]
    fn shutdown_is_queued_for_passive_level_flush() {
        assert_eq!(
            dispatch_policy(DriverDeviceKind::MountedVolume, DispatchMajor::Shutdown),
            DispatchPolicy::Queued
        );
    }

    /// # Panics
    ///
    /// Panics when lock-control IRPs bypass the actor that sequences oplock and byte-lock state.
    #[test]
    fn lock_control_is_queued_for_stream_synchronization() {
        assert_eq!(
            dispatch_policy(DriverDeviceKind::MountedVolume, DispatchMajor::LockControl),
            DispatchPolicy::Queued
        );
    }

    /// # Panics
    ///
    /// Panics when cleanup stops using the actor barrier after cancelling earlier pending IRPs.
    #[test]
    fn cleanup_runs_on_actor_after_pending_irps_are_cancelled() {
        assert_eq!(
            dispatch_policy(DriverDeviceKind::MountedVolume, DispatchMajor::Cleanup),
            DispatchPolicy::Queued
        );
    }

    /// # Panics
    ///
    /// Panics when close stops following create and cleanup on the same actor.
    #[test]
    fn close_runs_after_prior_file_object_operations() {
        assert_eq!(
            dispatch_policy(DriverDeviceKind::MountedVolume, DispatchMajor::Close),
            DispatchPolicy::Queued
        );
    }

    /// # Panics
    ///
    /// Panics when the named control device enters mounted-volume handle machinery or admits a
    /// lifecycle request through the reactor it is responsible for stopping.
    #[test]
    fn control_device_lifecycle_requests_are_immediate_and_mounts_remain_queued() {
        assert_eq!(
            dispatch_policy(DriverDeviceKind::Control, DispatchMajor::Create),
            DispatchPolicy::Immediate(ImmediateDispatch::OpenControl)
        );
        assert_eq!(
            dispatch_policy(DriverDeviceKind::Control, DispatchMajor::Cleanup),
            DispatchPolicy::Immediate(ImmediateDispatch::CleanupControl)
        );
        assert_eq!(
            dispatch_policy(DriverDeviceKind::Control, DispatchMajor::Close),
            DispatchPolicy::Immediate(ImmediateDispatch::CloseControl)
        );
        assert_eq!(
            dispatch_policy(DriverDeviceKind::Control, DispatchMajor::DeviceControl),
            DispatchPolicy::Immediate(ImmediateDispatch::ControlDeviceRequest)
        );
        assert_eq!(
            dispatch_policy(DriverDeviceKind::Control, DispatchMajor::FileSystemControl),
            DispatchPolicy::Queued
        );
        assert_eq!(
            dispatch_policy(DriverDeviceKind::Control, DispatchMajor::Read),
            DispatchPolicy::Immediate(ImmediateDispatch::Reject)
        );
    }

    /// # Panics
    ///
    /// Panics when flush loses its post-cleanup lane while the handle is open, or remains
    /// admissible after close begins.
    #[test]
    fn post_cleanup_requests_keep_one_lane_for_the_whole_live_handle() {
        for request in [PostCleanupRequest::FlushBuffers] {
            for state in [
                HandleAdmissionState::OpenHandle,
                HandleAdmissionState::CleanupDraining,
                HandleAdmissionState::CleanedHandle,
            ] {
                assert!(matches!(
                    post_cleanup_lane(state, request),
                    Ok(HandleOperationLane::PostCleanup(observed)) if observed == request
                ));
            }
            for state in [
                HandleAdmissionState::ClosingHandle,
                HandleAdmissionState::ClosedHandle,
            ] {
                assert!(matches!(
                    post_cleanup_lane(state, request),
                    Err(DriverError::FileClosed)
                ));
            }
        }
    }
}
